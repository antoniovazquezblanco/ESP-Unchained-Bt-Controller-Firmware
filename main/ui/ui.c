/* ---- State -------------------------------------------------------------- */
static esp_lcd_panel_handle_t s_panel;
static uint16_t *s_line;                    /* one text row: SCR_W x GLYPH */
static char s_buf[ROWS][COLS];              /* console text model */
static int s_col;                           /* cursor column on bottom row */
static bool s_dirty;
static bool s_in_esc;                       /* stripping an ANSI escape */
static StreamBufferHandle_t s_sb;
static vprintf_like_t s_prev;

/* ---- Drawing ------------------------------------------------------------ */
static void put_glyph(uint16_t *buf, int bufw, int px, int py, char ch, uint16_t fg)
{
    if (ch < 0x20 || ch > 0x7F) ch = ' ';
    const uint8_t *g = font8x8[ch - 0x20];
    for (int ry = 0; ry < 8; ry++) {
        uint8_t row = g[ry];
        uint16_t *p = &buf[(py + ry) * bufw + px];
        for (int cx = 0; cx < 8; cx++) {
            if (row & (1 << cx)) p[cx] = fg;
        }
    }
}

static void draw_topbar(void)
{
    uint16_t *bar = heap_caps_malloc(SCR_W * BAR_H * sizeof(uint16_t), MALLOC_CAP_DMA);
    if (!bar) return;
    for (int i = 0; i < SCR_W * BAR_H; i++) bar[i] = C_BAR_BG;
    int len = (int)strlen(TITLE);
    int x0 = (SCR_W - len * GLYPH) / 2;
    if (x0 < 0) x0 = 0;
    int y0 = (BAR_H - GLYPH) / 2;
    for (int i = 0; i < len && (x0 + i * GLYPH + GLYPH) <= SCR_W; i++) {
        put_glyph(bar, SCR_W, x0 + i * GLYPH, y0, TITLE[i], C_BAR_FG);
    }
    esp_lcd_panel_draw_bitmap(s_panel, 0, 0, SCR_W, BAR_H, bar);
    heap_caps_free(bar);
}

static void render_console(void)
{
    for (int r = 0; r < ROWS; r++) {
        for (int i = 0; i < SCR_W * GLYPH; i++) s_line[i] = C_LOG_BG;
        for (int c = 0; c < COLS; c++) {
            char ch = s_buf[r][c];
            if (ch != ' ') put_glyph(s_line, SCR_W, c * GLYPH, 0, ch, C_LOG_FG);
        }
        int y = BAR_H + r * GLYPH;
        esp_lcd_panel_draw_bitmap(s_panel, 0, y, SCR_W, y + GLYPH, s_line);
    }
}

/* ---- Console model ------------------------------------------------------ */
static void console_newline(void)
{
    memmove(s_buf[0], s_buf[1], (ROWS - 1) * COLS);
    memset(s_buf[ROWS - 1], ' ', COLS);
    s_col = 0;
}

static void console_putc(char c)
{
    if (s_in_esc) {                         /* strip ANSI colour escapes */
        if ((c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z')) s_in_esc = false;
        return;
    }
    if (c == 0x1B) { s_in_esc = true; return; }
    if (c == '\r') return;
    if (c == '\n') { console_newline(); return; }
    if (c == '\t') c = ' ';
    if (c < 0x20 || c > 0x7E) return;
    if (s_col >= COLS) console_newline();
    s_buf[ROWS - 1][s_col++] = c;
}

/* ---- Log hook + render task -------------------------------------------- */
static int log_vprintf(const char *fmt, va_list ap)
{
    char tmp[200];
    va_list ap2;
    va_copy(ap2, ap);
    int n = vsnprintf(tmp, sizeof(tmp), fmt, ap);
    int r = s_prev ? s_prev(fmt, ap2) : n;  /* keep the normal console */
    va_end(ap2);
    if (s_sb && n > 0) {
        size_t len = (n < (int)sizeof(tmp)) ? (size_t)n : sizeof(tmp) - 1;
        xStreamBufferSend(s_sb, tmp, len, 0);   /* non-blocking; drop if full */
    }
    return r;
}

static void ui_task(void *arg)
{
    char rx[128];
    for (;;) {
        size_t got = xStreamBufferReceive(s_sb, rx, sizeof(rx), pdMS_TO_TICKS(100));
        if (got) {
            for (size_t i = 0; i < got; i++) console_putc(rx[i]);
            s_dirty = true;
        }
        if (s_dirty) {
            render_console();
            s_dirty = false;
        }
    }
}

void ui_init(void)
{
    if (s_panel) return;                    /* already initialised */

    /* The panel is ours to bring up: callers only ever talk to ui.h. */
    esp_err_t ret = display_init();
    if (ret != ESP_OK) {
        ESP_LOGW(TAG, "display init failed: %s", esp_err_to_name(ret));
        return;
    }

    s_panel = display_panel();
    if (!s_panel) return;                   /* display not up */

    s_line = heap_caps_malloc(SCR_W * GLYPH * sizeof(uint16_t), MALLOC_CAP_DMA);
    if (!s_line) { s_panel = NULL; return; }

    for (int r = 0; r < ROWS; r++) memset(s_buf[r], ' ', COLS);
    s_col = 0;

    draw_topbar();
    render_console();                       /* clears the log area */

    s_sb = xStreamBufferCreate(2048, 1);
    if (!s_sb) return;
    xTaskCreate(ui_task, "ui", 4096, NULL, 5, NULL);
    s_prev = esp_log_set_vprintf(log_vprintf);
}

